class TestAPCRControllerDiagnostics:
    """Test suite for APCR diagnostics generated by controller."""

    def test_apcr_diagnostics_keys_generated(self):
        """Test that controller generates all expected APCR diagnostic keys."""
        from wheeled_biped.controllers.sagittal_velocity_damped_balance_controller import (
            SagittalVelocityDampedBalanceController,
            SagittalAuthoritySchedule,
        )

        # Create controller with APCR enabled
        schedule = SagittalAuthoritySchedule(
            profile_name="test_apcr",
            applies_to_variants=("low_0p300",),
            enable_active_pitch_crossing=True,
            active_pitch_crossing_recovery_gate_mode=True,
            apc_inner_exit_m=0.07,
            apc_outer_enter_m=0.10,
            apc_opposite_overshoot_m=0.00,
        )

        controller = SagittalVelocityDampedBalanceController(
            authority_schedule=schedule,
        )

        # Call compute with correct signature
        tau, diagnostics = controller.compute(
            pitch_x_rad=0.05,
            pitch_rate_x_rad_s=0.0,
            sagittal_velocity_m_s=0.0,
            wheel_vel_left_rad_s=0.0,
            wheel_vel_right_rad_s=0.0,
            sagittal_position_error_m=0.0,
            com_z_m=0.35,
            roll_y_rad=0.0,
            contact_valid=True,
            height_variant_name="low_0p300",
        )

        # Verify expected APCR diagnostic keys exist
        expected_keys = [
            "active_pitch_crossing_enabled",
            "active_pitch_crossing_state",
            "active_pitch_crossing_active",
            "active_pitch_crossing_inner_exit_m",
            "active_pitch_crossing_outer_enter_m",
            "active_pitch_crossing_recovery_gate_mode",
            "final_wheel_tau_with_apc",
            "final_wheel_tau_without_apc",
        ]

        for key in expected_keys:
            assert key in diagnostics, f"Expected APCR diagnostic key '{key}' not found"

        # Verify APCR is enabled
        assert diagnostics["active_pitch_crossing_enabled"] is True

        # Verify recovery gate mode is enabled
        assert diagnostics["active_pitch_crossing_recovery_gate_mode"] is True

        # Verify threshold values are correct
        assert diagnostics["active_pitch_crossing_inner_exit_m"] == 0.07
        assert diagnostics["active_pitch_crossing_outer_enter_m"] == 0.10


