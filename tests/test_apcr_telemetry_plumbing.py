class TestAPCRTelemetrySourceInspection:
    """Test suite for APCR telemetry plumbing via source inspection."""

    def test_apcr_telemetry_initialization_in_simulator(self):
        """Test that APCR telemetry fields are initialized in simulate_hierarchical_controller.py."""
        import ast
        import pathlib

        # Read the simulator source file
        simulator_path = pathlib.Path("f:/ROBOTCUATAO/Wheeled-bipedal-robot-simulation/scripts/simulate_hierarchical_controller.py")
        source = simulator_path.read_text()

        # Parse the source into an AST
        tree = ast.parse(source)

        # Look for telemetry initialization that includes active_pitch_crossing fields
        apcr_fields_found = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Dict):
                # Look for keys that look like telemetry field initialization
                for key in node.keys:
                    if isinstance(key, ast.Constant) and isinstance(key.value, str):
                        if "active_pitch_crossing" in key.value:
                            apcr_fields_found.append(key.value)

        # Verify key APCR fields are initialized
        critical_apcr_fields = [
            "active_pitch_crossing_enabled",
            "active_pitch_crossing_state",
            "active_pitch_crossing_active",
        ]

        for field in critical_apcr_fields:
            assert field in apcr_fields_found, (
                f"APCR telemetry field '{field}' not found in telemetry initialization"
            )

