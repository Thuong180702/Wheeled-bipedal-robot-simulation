"""Full Step D validation using real simulation telemetry.

This module parses the existing
``outputs/step_d_all/step_d_all_metrics.csv`` (generated by
``scripts/run_step_d_all.py``) and aggregates the worst-case hip-yaw
metric across all D1-D6 cases for the given profile tag.

Returns
-------
dict
    * ``hip_yaw_abs_max`` – worst-case hip-yaw magnitude across D1-D6
      for the requested profile.
    * ``d4_d5_hip_yaw_abs_max`` – worst-case restricted to D4 and D5.
    * ``hip_yaw_abs_max_per_case`` – dict of per-case worst-case values.
    * ``fell_any`` – whether any case for the profile resulted in fall.
    * ``validation_source`` – always ``"real_simulation"``.

Raises
------
RuntimeError
    If the CSV is missing or the profile tag is unknown.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Dict


ROOT = Path(__file__).resolve().parent.parent.parent
STEP_D_CSV = ROOT / "outputs" / "step_d_all" / "step_d_all_metrics.csv"

PROFILE_TO_TAG = {
    "calibrated_support_position_outer_loop_pitch_ref_v2": "A",
    "physics_equilibrium_feedforward_outer_loop": "B",
    "physics_equilibrium_feedforward_outer_loop_low_band_support_v2": "C",
    "physics_equilibrium_feedforward_outer_loop_low_band_support_v2_mode_hip_yaw_div_v1": "D",
}

HIP_YAW_COL = "hip_yaw_abs_max_rad"
FELL_COL = "fell"

ALL_CASES = (
    "D1_small_push_high",
    "D2_medium_push_high",
    "D3_small_push_low",
    "D4_medium_push_low",
    "D5_large_push_high",
    "D6_random_push_high",
)
D4_D5_CASES = ("D4_medium_push_low", "D5_large_push_high")


def _read_csv(path: Path) -> list[dict]:
    with path.open("r", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _f(row: dict, key: str) -> float:
    value = row.get(key, "")
    if value in ("", None, "nan"):
        return 0.0
    try:
        return float(value)
    except ValueError:
        return 0.0


def _b(row: dict, key: str) -> bool:
    return str(row.get(key, "false")).strip().lower() in ("true", "1")


def run_full_step_d(profile: str) -> Dict[str, object]:
    """Parse the Step D CSV and return aggregated metrics for *profile*."""
    if not STEP_D_CSV.exists():
        raise RuntimeError(
            f"Step D CSV missing: {STEP_D_CSV}. Run scripts/run_step_d_all.py first."
        )
    rows = _read_csv(STEP_D_CSV)
    tag = PROFILE_TO_TAG.get(profile)
    if tag is None:
        raise RuntimeError(
            f"Unknown profile {profile!r}; expected one of {list(PROFILE_TO_TAG)}"
        )

    profile_rows = [r for r in rows if r.get("profile") == tag]
    if not profile_rows:
        raise RuntimeError(
            f"No rows for profile={profile} (tag={tag}) in {STEP_D_CSV}. "
            f"Have profiles: {sorted({r.get('profile') for r in rows})}"
        )

    per_case: Dict[str, float] = {}
    fell_any = False
    for case in ALL_CASES:
        case_rows = [r for r in profile_rows if r.get("case_id") == case]
        if not case_rows:
            per_case[case] = 0.0
            continue
        max_hy = max(_f(r, HIP_YAW_COL) for r in case_rows)
        per_case[case] = max_hy
        if any(_b(r, FELL_COL) for r in case_rows):
            fell_any = True

    overall = max(per_case.values()) if per_case else 0.0
    d4_d5 = max(per_case.get(c, 0.0) for c in D4_D5_CASES)

    return {
        "hip_yaw_abs_max": float(overall),
        "d4_d5_hip_yaw_abs_max": float(d4_d5),
        "hip_yaw_abs_max_per_case": per_case,
        "fell_any": bool(fell_any),
        "validation_source": "real_simulation",
    }