"""D4/D5 validation using real simulation telemetry.

This module parses the existing
``outputs/hip_yaw_push_limit_architecture_fix/d4_d5_validation/d4_d5_metrics.csv``
(generated by ``scripts/run_d4_d5_hip_yaw_validation.py``) and returns the
worst-case hip-yaw metric across the D4 and D5 push cases for the given
profile tag.

The function returns a dictionary with at minimum:

* ``hip_yaw_abs_max`` – maximum absolute hip-yaw angle (rad) observed
  across D4 and D5 cases for the given profile.
* ``validation_source`` – ``"real_simulation"`` if the real CSV was found
  and parsed; ``"stub"`` otherwise.

If the CSV is missing or cannot be parsed, the function raises
``RuntimeError`` so downstream gate code aborts rather than silently
accepting stub values.
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Dict


ROOT = Path(__file__).resolve().parent.parent.parent
D4_D5_CSV = (
    ROOT
    / "outputs"
    / "hip_yaw_push_limit_architecture_fix"
    / "d4_d5_validation"
    / "d4_d5_metrics.csv"
)

TARGET_CASES = {"D4_medium_push_low", "D5_large_push_high"}

PROFILE_TO_TAG = {
    "calibrated_support_position_outer_loop_pitch_ref_v2": "A",
    "physics_equilibrium_feedforward_outer_loop": "B",
    "physics_equilibrium_feedforward_outer_loop_low_band_support_v2": "C",
    "physics_equilibrium_feedforward_outer_loop_low_band_support_v2_mode_hip_yaw_div_v1": "D",
}

HIP_YAW_COL = "hip_yaw_abs_max_rad"


def _read_csv(path: Path) -> list[dict]:
    with path.open("r", newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _row_metric(row: dict) -> float:
    value = row.get(HIP_YAW_COL, "")
    if value in ("", None, "nan"):
        return 0.0
    try:
        return float(value)
    except ValueError:
        return 0.0


def run_and_check(profile: str) -> Dict[str, float]:
    """Parse the D4/D5 CSV and return aggregated hip-yaw metrics for *profile*.

    The ``profile`` argument is the canonical controller profile name. It is
    translated to the corresponding row tag (``A``/``B``/``C``/``D``) via
    :data:`PROFILE_TO_TAG`.

    Returns
    -------
    dict
        Keys: ``hip_yaw_abs_max``, ``d4_hip_yaw_abs_max``,
        ``d5_hip_yaw_abs_max``, ``validation_source``.

    Raises
    ------
    RuntimeError
        If the CSV is missing or has no rows for the requested profile and
        target cases.
    """
    if not D4_D5_CSV.exists():
        raise RuntimeError(
            f"D4/D5 validation CSV missing: {D4_D5_CSV}. "
            "Run scripts/run_d4_d5_hip_yaw_validation.py first."
        )

    rows = _read_csv(D4_D5_CSV)
    tag = PROFILE_TO_TAG.get(profile)
    if tag is None:
        raise RuntimeError(
            f"Unknown profile {profile!r}; expected one of {list(PROFILE_TO_TAG)}"
        )

    target_rows = [
        r
        for r in rows
        if r.get("case_id") in TARGET_CASES and r.get("profile") == tag
    ]
    if not target_rows:
        raise RuntimeError(
            f"No rows for profile={profile} (tag={tag}) in {D4_D5_CSV}. "
            f"Have profiles: {sorted({r.get('profile') for r in rows})}"
        )

    d4_row = next(
        (r for r in target_rows if r["case_id"] == "D4_medium_push_low"), None
    )
    d5_row = next(
        (r for r in target_rows if r["case_id"] == "D5_large_push_high"), None
    )

    d4_hy = _row_metric(d4_row) if d4_row else 0.0
    d5_hy = _row_metric(d5_row) if d5_row else 0.0

    return {
        "hip_yaw_abs_max": float(max(d4_hy, d5_hy)),
        "d4_hip_yaw_abs_max": float(d4_hy),
        "d5_hip_yaw_abs_max": float(d5_hy),
        "validation_source": "real_simulation",
    }